/* -----------------------------
Q1. Customer Order Summary

Problem:
Generate a report showing each customer along with the total number
of orders they have placed.
------------------------------*/

-- Solution 1: LEFT JOIN

SELECT c.customer_id,
       c.name,
       COUNT(o.order_id) AS total_orders
FROM customers c
LEFT JOIN orders o
       ON c.customer_id = o.customer_id
GROUP BY c.customer_id, c.name;

-- Solution 2: Correlated Subquery

SELECT c.customer_id,
       c.name,
       (SELECT COUNT(*)
          FROM orders o
         WHERE o.customer_id = c.customer_id) AS total_orders
FROM customers c;

/*
Interview Note:
LEFT JOIN + GROUP BY is most common.
Correlated subquery demonstrates another approach.
*/


