WITH customer_spend AS (
     SELECT customer_id,
            SUM(order_value) total_spend
     FROM orders
     GROUP BY customer_id
)
SELECT customer_id,
       total_spend,
       CASE
           WHEN total_spend > 50000 THEN 'Gold'
           WHEN total_spend >= 10000 THEN 'Silver'
           ELSE 'Bronze'
       END AS spending_tier
FROM customer_spend;


