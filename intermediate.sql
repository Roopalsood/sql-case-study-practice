/* -----------------------------
Q41. Customer Active/Inactive Classification

Problem:
Classify customers as Active or Inactive based on the is_active flag.
------------------------------*/

-- Solution 1

SELECT customer_id,
       name,
       CASE
           WHEN is_active = 'Y' THEN 'Active'
           ELSE 'Inactive'
       END AS customer_status
FROM customers;

-- Solution 2

SELECT customer_id,
       name,
       DECODE(is_active,
              'Y', 'Active',
              'Inactive') AS customer_status
FROM customers;

/*
Interview Note:
CASE is ANSI SQL standard.
DECODE is Oracle-specific.
*/


