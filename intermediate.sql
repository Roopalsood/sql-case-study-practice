       total_spend,
       CASE
           WHEN total_spend < 10000 THEN 'Bronze'
           WHEN total_spend <= 50000 THEN 'Silver'
           ELSE 'Gold'
       END AS spending_tier
FROM (
      SELECT customer_id,
             SUM(order_value) AS total_spend
      FROM orders
      GROUP BY customer_id
);

