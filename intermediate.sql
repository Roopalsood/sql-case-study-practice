/* -----------------------------
Q26. Employees Earning Above Company Average Salary

Problem:
Find employees whose salary is higher than the company average salary.
------------------------------*/

-- Solution 1: Scalar Subquery

SELECT employee_id,
       name,
       salary
FROM employees
WHERE salary >
      (SELECT AVG(salary)
       FROM employees);

-- Solution 2: CTE

WITH avg_salary_cte AS (
    SELECT AVG(salary) AS avg_salary
    FROM employees
)
SELECT e.employee_id,
       e.name,
       e.salary
FROM employees e
CROSS JOIN avg_salary_cte a
WHERE e.salary > a.avg_salary;

/*
Interview Note:
One of the most common SQL interview questions.
*/


/* -----------------------------
Q27. Employees Earning Above Department Average Salary

Problem:
Find employees whose salary is greater than the average salary
of their department.
------------------------------*/

-- Solution 1: Correlated Subquery

SELECT employee_id,
       name,
       department,
       salary
FROM employees e
WHERE salary >
      (
          SELECT AVG(salary)
          FROM employees
          WHERE department = e.department
      );

-- Solution 2: Inline View

SELECT e.*
FROM employees e
JOIN (
        SELECT department,
               AVG(salary) AS avg_salary
        FROM employees
        GROUP BY department
     ) d
ON e.department = d.department
WHERE e.salary > d.avg_salary;

/*
Interview Note:
Classic correlated subquery question.
*/


