/* -----------------------------
Q50. High-Value vs Low-Value Customer Classification

Problem:
Classify customers as High Value or Low Value based on
whether their spending exceeds the average customer spend.
------------------------------*/

-- Solution 1

SELECT customer_id,
       total_spend,
       CASE
           WHEN total_spend >
                (
                  SELECT AVG(total_spend)
                  FROM (
                        SELECT SUM(order_value) total_spend
                        FROM orders
                        GROUP BY customer_id
                  )
                )
           THEN 'High Value'
           ELSE 'Low Value'
       END AS customer_type
FROM (
      SELECT customer_id,
             SUM(order_value) total_spend
      FROM orders
      GROUP BY customer_id
);

-- Solution 2

WITH customer_spend AS (
     SELECT customer_id,
            SUM(order_value) total_spend
     FROM orders
     GROUP BY customer_id
),
avg_spend AS (
     SELECT AVG(total_spend) avg_spend
     FROM customer_spend
)
SELECT c.customer_id,
       c.total_spend,
       CASE
           WHEN c.total_spend > a.avg_spend
                THEN 'High Value'
           ELSE 'Low Value'
       END AS customer_type
FROM customer_spend c
CROSS JOIN avg_spend a;

